func (g *gen) namedSecrets() []Row {
	var rows []Row
	for i, k := range secretKeys {
		// Three weak values. Only the name can decide these.
		for j := 0; j < 3; j++ {
			v := g.weak(i + j)
			rows = append(rows, Row{Key: k, Value: v, Want: Secret,
				Sensitive: []string{v}, Note: "the name says secret and the value is weak"})
		}
		// Two random values. The name and the value both point one way.
		for _, v := range []string{g.hex(32), g.alnum(40)} {
			rows = append(rows, Row{Key: k, Value: v, Want: Secret,
				Sensitive: []string{v}, Note: "the name says secret and the value is random"})
		}
	}
	return rows
}

