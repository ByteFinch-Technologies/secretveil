// Counts reports how many rows of each label the corpus holds. The tests print
// it, so a change in the size of the set is visible in the log.
func Counts(rows []Row) map[Want]int {
	out := map[Want]int{}
	for _, r := range rows {
		out[r.Want]++
	}
	return out
}

// Keys returns every distinct variable name in the corpus, sorted.
func Keys(rows []Row) []string {
	seen := map[string]bool{}
	var out []string
	for _, r := range rows {
		if !seen[r.Key] {
			seen[r.Key] = true
			out = append(out, r.Key)
		}
	}
	sort.Strings(out)
	return out
}
