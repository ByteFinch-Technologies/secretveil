// ----------------------------------------------------------- bland random

// blandRandom is the hardest set. The name says nothing and the value carries
// no vendor prefix, so only the entropy rule can save these. Short lengths are
// where the measurement showed the rule failing.
func (g *gen) blandRandom() []Row {
	names := []string{"ACME_BLURB", "SETTING", "OPTION_A", "WIDGET", "THING", "PARAM"}
	kinds := []struct {
		name string
		make func(int) string
	}{
		{"hex", g.hex},
		{"alnum", g.alnum},
		{"base64", g.base64},
	}
	var rows []Row
	for _, n := range []int{24, 32, 40, 48, 64} {
		for _, k := range kinds {
			for i := 0; i < 4; i++ {
				v := k.make(n)
				rows = append(rows, Row{
					Key: names[(n+i)%len(names)], Value: v, Want: Secret,
					Sensitive: []string{v},
					Note:      fmt.Sprintf("a random %s token of %d characters under a name that says nothing", k.name, n),
				})
			}
		}
	}
	return rows
}

// ------------------------------------------------------------ composites

// composites hold a readable part and a secret part. The readable part must
// survive, because the agent needs it, and the secret part must not.
func (g *gen) composites() []Row {
	var rows []Row
	for i := 0; i < 4; i++ {
		pw := g.alnum(16)
		v := fmt.Sprintf("postgres://appuser:%s@db%d.internal:5432/appdb", pw, i)
		rows = append(rows, Row{Key: "DATABASE_URL", Value: v, Want: Secret,
			Sensitive: []string{pw}, Note: "a url that carries a password"})
	}
	for i := 0; i < 3; i++ {
		pw := g.alnum(14)
		v := fmt.Sprintf("mongodb+srv://svc:%s@cluster%d.mongodb.net/app", pw, i)
		rows = append(rows, Row{Key: "MONGO_URI", Value: v, Want: Secret,
			Sensitive: []string{pw}, Note: "a url that carries a password"})
	}
	for i := 0; i < 3; i++ {
		tok := g.alnum(24)
		v := fmt.Sprintf("https://api.example.com/v%d/feed?format=json&token=%s", i+1, tok)
		rows = append(rows, Row{Key: "FEED_URL", Value: v, Want: Secret,
			Sensitive: []string{tok}, Note: "a url that carries a token in the query"})
	}
	// Both at once. One field veiled and the other left in the clear is the
	// failure this set exists to catch.
	for i := 0; i < 3; i++ {
		pw, tok := g.alnum(14), g.alnum(22)
		v := fmt.Sprintf("https://svcuser:%s@gateway%d.example.com/pull?api_key=%s", pw, i, tok)
		rows = append(rows, Row{Key: "GATEWAY_URL", Value: v, Want: Secret,
			Sensitive: []string{pw, tok}, Note: "a url that carries a password and a token"})
	}
	for i := 0; i < 3; i++ {
		pw := g.alnum(18)
		v := fmt.Sprintf("Server=tcp:sql%d.database.windows.net,1433;Database=app;User ID=svc;Password=%s;Encrypt=true", i, pw)
		rows = append(rows, Row{Key: "SQL_CONNECTION", Value: v, Want: Secret,
			Sensitive: []string{pw}, Note: "a connection string that carries a password"})
	}
	for i := 0; i < 3; i++ {
		tok := g.alnum(32)
		rows = append(rows, Row{Key: "UPSTREAM_AUTH", Value: "Bearer " + tok, Want: Secret,
			Sensitive: []string{tok}, Note: "an authorization header value"})
	}
	// A query credential list long enough to reach the tenth parameter, which
	// is where the reference naming breaks.
	var parts []string
	var sens []string
	names := []string{"token", "key", "api_key", "apikey", "password", "secret", "sig", "signature", "access_token", "auth"}
	for _, n := range names {
		t := g.alnum(18)
		parts = append(parts, n+"="+t)
		sens = append(sens, t)
	}
	rows = append(rows, Row{
		Key: "MULTI_URL", Value: "https://api.example.com/x?" + strings.Join(parts, "&"),
		Want: Secret, Sensitive: sens, Note: "ten credentials in one query, which is where the reference naming breaks",
	})
	return rows
}

