// Package corpus builds the labelled set of values that the classifier tests
// measure against.
//
// Every value here is made by this code from a fixed seed. No value is typed
// in by hand, and no value came from a real system.
//
// The rows are never written to a file of this repository. Each one has the
// shape of a real credential, because a value that does not look like a
// credential measures nothing, and a file of such values is wrong in a public
// repository: the host refuses the push, and a reader cannot tell a made-up
// key from a real one. TestNoCorpusValueIsStoredInTheRepository holds that
// line by reading every file of the tree.
//
// The package is imported by the classifier tests and by the adversarial test
// that runs a real init over the whole set. No command imports it, and
// test/nonetwork fails if one ever does.
package corpus

import (
	"fmt"
	"math/rand"
	"sort"
	"strings"
)

// Seed fixes the generator. Change it and every value changes, so do not
// change it without a reason.
const Seed = 20260819

// Want says what the classifier must do with a row.
type Want string

const (
	// Secret means no part named in Sensitive may survive into the file the
	// agent reads.
	Secret Want = "secret"
	// Open means the value must reach the agent in full.
	Open Want = "open"
)

// Row is one labelled example.
type Row struct {
	Key   string
	Value string
	Want  Want
	// Sensitive lists the parts of Value that must not survive. It holds one
	// entry for a whole secret and one entry per field for a composite. It is
	// empty for an open row.
	Sensitive []string
	// Note says why the row is labelled the way it is. It is for the human who
	// reads the file, and no test reads it.
	Note string
}

// Generate returns the whole corpus, in a stable order.
func Generate() []Row {
	g := &gen{r: rand.New(rand.NewSource(Seed))}
	var rows []Row
	rows = append(rows, g.namedSecrets()...)
	rows = append(rows, g.vendorShapes()...)
	rows = append(rows, g.blandRandom()...)
	rows = append(rows, g.composites()...)
	rows = append(rows, g.configNames()...)
	rows = append(rows, g.publicPrefixes()...)
	rows = append(rows, g.plainValues()...)
	for i, row := range rows {
		if err := row.check(); err != nil {
			panic(fmt.Sprintf("corpus row %d (%s): %v", i, row.Key, err))
		}
	}
	return rows
}

// check refuses a row that would break the file format or the labelling.
func (r Row) check() error {
	for _, s := range []string{r.Key, r.Value, r.Note} {
		if strings.ContainsAny(s, "\t\n\r") {
			return fmt.Errorf("a tab or a newline is not allowed")
		}
	}
	switch r.Want {
	case Secret:
		if len(r.Sensitive) == 0 {
			return fmt.Errorf("a secret row must name what is sensitive")
		}
		for _, s := range r.Sensitive {
			if s == "" || strings.Contains(s, " ") {
				return fmt.Errorf("a sensitive part must not be empty or hold a space")
			}
			if !strings.Contains(r.Value, s) {
				return fmt.Errorf("the sensitive part %q is not in the value", s)
			}
		}
	case Open:
		if len(r.Sensitive) != 0 {
			return fmt.Errorf("an open row must name nothing sensitive")
		}
	default:
		return fmt.Errorf("the want %q is not known", r.Want)
	}
	return nil
}

// ------------------------------------------------------------------ reading

// Marshal renders the corpus as tab separated text.
//
// Nothing writes the result to a file. Two tests compare two calls to prove
// the generator is stable, and a developer can print it to read the rows.
func Marshal(rows []Row) string {
	var b strings.Builder
	b.WriteString("# The labelled corpus for the secret classifier.\n")
	b.WriteString("# Every value is generated by internal/corpus from a fixed seed.\n")
	b.WriteString("# Do not edit this file. Change internal/corpus and run:\n")
	b.WriteString("#   go test ./internal/classify -run TestEveryCorpusValueIsGenerated -update\n")
	b.WriteString("#\n")
	b.WriteString("# key\tvalue\twant\tsensitive\tnote\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "%s\t%s\t%s\t%s\t%s\n",
			r.Key, r.Value, r.Want, strings.Join(r.Sensitive, " "), r.Note)
	}
	return b.String()
}

// ------------------------------------------------------------- the values

type gen struct{ r *rand.Rand }

const (
	hexDigits    = "0123456789abcdef"
	alnumDigits  = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
	base64Digits = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
	upperDigits  = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
)

func (g *gen) pick(alphabet string, n int) string {
	b := make([]byte, n)
	for i := range b {
		b[i] = alphabet[g.r.Intn(len(alphabet))]
	}
	return string(b)
}

func (g *gen) hex(n int) string    { return g.pick(hexDigits, n) }
func (g *gen) alnum(n int) string  { return g.pick(alnumDigits, n) }
func (g *gen) base64(n int) string { return g.pick(base64Digits, n) }

// weak returns a short password that no entropy rule can catch. Only the name
// of the variable can save a value like this, which is what makes it the sharp
// test of the name rules.
func (g *gen) weak(i int) string {
	words := []string{"Hunter2!", "letmein", "changeme", "Passw0rd", "admin123", "s3cret", "qwerty1", "P@ssw0rd1"}
	return words[i%len(words)]
}

